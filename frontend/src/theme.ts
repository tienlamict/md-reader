// Light and dark stylesheets are both loaded; their `media` attribute decides
// which one applies, so "system" simply follows prefers-color-scheme.
// Printing always uses the light sheets (dark text on white paper).
import lightCssUrl from 'github-markdown-css/github-markdown-light.css?url';
import darkCssUrl from 'github-markdown-css/github-markdown-dark.css?url';

export type Theme = 'system' | 'light' | 'dark';

type Sheet = HTMLLinkElement | HTMLStyleElement;

const lightSheets: Sheet[] = [];
const darkSheets: Sheet[] = [];
const darkQuery = window.matchMedia('(prefers-color-scheme: dark)');
const listeners: ((dark: boolean) => void)[] = [];

let current: Theme = 'system';
let highlight = {light: '', dark: ''};

function addLink(href: string): HTMLLinkElement {
    const link = document.createElement('link');
    link.rel = 'stylesheet';
    link.href = href;
    document.head.appendChild(link);
    return link;
}

function addStyle(css: string): HTMLStyleElement {
    const style = document.createElement('style');
    style.textContent = css;
    document.head.appendChild(style);
    return style;
}

lightSheets.push(addLink(lightCssUrl));
darkSheets.push(addLink(darkCssUrl));

/** Adds the syntax-highlighting CSS generated by Go for both themes. */
export function addHighlightCss(light: string, dark: string) {
    highlight = {light, dark};
    lightSheets.push(addStyle(light));
    darkSheets.push(addStyle(dark));
}

/** The chroma CSS for both themes (used when exporting HTML). */
export function highlightCss() {
    return highlight;
}

/** Whether the document is currently shown in dark colours. */
export function isDark(): boolean {
    return current === 'dark' || (current === 'system' && darkQuery.matches);
}

/** Calls fn whenever the effective (light/dark) appearance changes. */
export function onAppearanceChange(fn: (dark: boolean) => void) {
    listeners.push(fn);
}

let lastDark = isDark();

function notify() {
    const dark = isDark();
    if (dark === lastDark) return;
    lastDark = dark;
    listeners.forEach((fn) => fn(dark));
}

darkQuery.addEventListener('change', notify);

export function applyTheme(theme: Theme) {
    current = theme === 'light' || theme === 'dark' ? theme : 'system';
    const media: Record<Theme, [string, string]> = {
        system: ['print, (prefers-color-scheme: light)', 'screen and (prefers-color-scheme: dark)'],
        light: ['all', 'not all'],
        dark: ['print', 'screen'],
    };
    const [light, dark] = media[current];
    lightSheets.forEach((s) => (s.media = light));
    darkSheets.forEach((s) => (s.media = dark));
    if (current === 'system') {
        delete document.documentElement.dataset.theme;
    } else {
        document.documentElement.dataset.theme = current;
    }
    notify();
}
